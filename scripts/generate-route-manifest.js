// Regenerates lib/route-manifest.ts: the set of URL paths that have an app/**/page.tsx.
// Used by components/Breadcrumbs.tsx so ancestor segments with no page are not rendered as dead links.
// Run: node scripts/generate-route-manifest.js
const fs = require('fs');
const path = require('path');

const appDir = path.join(__dirname, '..', 'app');
const routes = [];

function walk(dir, segs) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      // route groups "(x)" don't appear in the URL; skip private/api folders
      if (entry.name === 'api' || entry.name.startsWith('_')) continue;
      const isGroup = entry.name.startsWith('(') && entry.name.endsWith(')');
      walk(path.join(dir, entry.name), isGroup ? segs : [...segs, entry.name]);
    } else if (/^page\.(tsx|ts|jsx|js)$/.test(entry.name)) {
      routes.push(segs.join('/'));
    }
  }
}
walk(appDir, []);
routes.sort();

const out = `// GENERATED by scripts/generate-route-manifest.js - do not hand-edit.
// URL paths (no leading slash, dynamic segments as [param]) that have a page.tsx.
export const PAGE_ROUTES: ReadonlySet<string> = new Set([
${routes.map((r) => `  '${r}',`).join('\n')}
]);
`;
fs.writeFileSync(path.join(__dirname, '..', 'lib', 'route-manifest.ts'), out);
console.log(`Wrote ${routes.length} routes`);
